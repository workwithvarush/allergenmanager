export async function generateMetadata({ params }: PageProps<"/venues/[venueId]/archive/[ref]">): Promise<Metadata> {
  const { ref } = await params;
  return { title: `${ref} · Change log archive · Allergen Manager` };
}

/** One monthly change log archive, laid out as A4 pages to print or save as PDF. */
export default function ArchiveDocumentPage({ params, searchParams }: PageProps<"/venues/[venueId]/archive/[ref]">) {
  return (
    <Suspense fallback={<DocumentLoading />}>
      <ArchiveDocument params={params} searchParams={searchParams} />
    </Suspense>
  );
}

const shortDate = new Intl.DateTimeFormat("en-GB", { day: "numeric", month: "short", timeZone: "UTC" });
const longDate = new Intl.DateTimeFormat("en-GB", { day: "numeric", month: "short", year: "numeric", timeZone: "UTC" });
const utc = (isoDate: string) => new Date(`${isoDate}T00:00:00Z`);

/** "15 Oct 2026 · 23:54" */
const generatedLabel = (at: string) => `${longDate.format(utc(at.slice(0, 10)))} · ${at.slice(11, 16)}`;

async function ArchiveDocument({
  params,
  searchParams,
}: {
  params: Promise<{ venueId: string; ref: string }>;
  searchParams: Promise<Record<string, string | string[] | undefined>>;
}) {
  const [{ venueId, ref }, query] = await Promise.all([params, searchParams]);
  const venue = VENUES.find((v) => v.id === venueId && v.available);
  if (!venue) notFound();
  await connection();
  const user = await getSessionUser();
  if (!canViewArchive(user.role)) {
    return (
      <div className={styles.denied}>
        <h1>Change log archive</h1>
        <p>Change log archives are available to chefs, supervisors and F&amp;B managers.</p>
      </div>
    );
  }
  const archive = (await getArchives(venue.id)).find((a) => a.ref === ref);
  if (!archive) notFound();

  const pages = paginateArchive(archive.groups);
  const total = pages.length + 1;
  const partialTag = archive.partial ? " · PARTIAL" : "";
  const month = formatMonth(archive.month);
  const coverage = `${Number(archive.from.slice(8))}–${longDate.format(utc(archive.to))}`;
  const footerNote = "This record is fixed at time of generation and cannot be edited.";
  const footerRight = (page: number) => `${archive.ref} · Generated ${generatedLabel(archive.generatedAt)} · Page ${page} of ${total}${partialTag}`;

  return (
    <>
      <div className={styles.toolbar} data-print-hide>
        <Link href={`/venues/${venue.id}/archive`} className="btn btn-secondary btn-sm">
          ‹ Archive
        </Link>
        <span className={styles.toolbarRef}>{archive.ref}</span>
        <PrintArchiveButton />
      </div>
      <div data-print-hide>
        <OverflowWarning />
        {/* Arrived from "Generate archive" but this month's had already been issued — e.g. by someone else meanwhile. */}
        {query.existing === "1" && (
          <div className={`banner banner-info ${styles.notice}`} role="status">
            <div className="banner-body">
              This month&apos;s archive had already been generated by {archive.issuedBy.name} at{" "}
              {generatedLabel(archive.generatedAt)}, so it wasn&apos;t generated again — an archive can&apos;t be
              changed once issued.
            </div>
          </div>
        )}
      </div>

      <div className={styles.desk}>
        <Cover
          archive={archive}
          venueName={venue.name}
          month={month}
          coverage={coverage}
          footer={<Footer note={footerNote} right={footerRight(1)} />}
        />
        {(pages.length ? pages : [null]).map((blocks, i) => (
          <Page key={i} footer={<Footer note={footerNote} right={footerRight(i + 2)} />}>
            <header className={styles.pageHeader}>
              <span className={styles.pageHeaderTitle}>
                {venue.name} · Change Log Archive · {month}
              </span>
              <span className={styles.pageHeaderRef}>
                {archive.ref}
                {partialTag}
              </span>
            </header>
            {blocks === null ? (
              <p className={styles.emptyPeriod}>No changes recorded for this period.</p>
            ) : (
              blocks.map((block) =>
                block.kind === "heading" ? (
                  <section key={`${block.group.eventId}-${block.continued}`} className={styles.group}>
                    <div className={styles.groupHead}>
                      <h2 className={styles.groupName}>
                        {block.group.name}
                        {block.continued && " (continued)"}
                      </h2>
                      <span className={styles.groupStamp}>{block.group.stamp}</span>
                    </div>
                    <p className={styles.groupMeta}>{block.group.meta}</p>
                  </section>
                ) : (
                  <div key={block.entry.id} className={styles.entry}>
                    <span className={styles.entryTime}>
                      {shortDate.format(utc(block.entry.at.slice(0, 10)))} · {block.entry.at.slice(11, 16)}
                    </span>
                    <span className={`${logStyles.dot} ${logStyles[block.entry.type]} ${styles.entryDot}`} aria-hidden="true" />
                    <div className={styles.entryBody}>
                      <p className={styles.entryLine}>
                        <strong>{block.entry.name}</strong>
                        <span className={`${logStyles.role} ${logStyles[roleClass(block.entry.role)]}`}>
                          {block.entry.role}
                        </span>
                        <span>— {block.entry.text}</span>
                        {block.entry.type === "warn" && <span className="sr-only">(after printing)</span>}
                      </p>
                      <p className={styles.entryEmail}>{block.entry.email}</p>
                    </div>
                  </div>
                ),
              )
            )}
          </Page>
        ))}
      </div>
    </>
  );
}

/** Page 1: title, coverage, partial warning and summary figures. */
function Cover({
  archive,
  venueName,
  month,
  coverage,
  footer,
}: {
  archive: ArchiveRecord;
  venueName: string;
  month: string;
  coverage: string;
  footer: ReactNode;
}) {
  const summary = archiveSummary(archive);
  const figures = [
    { value: summary.entries, label: "Total entries", sub: `Across ${summary.events} ${summary.events === 1 ? "event" : "events"}` },
    { value: summary.events, label: "Events covered", sub: coverage },
    { value: summary.contributors.length, label: "Contributors", sub: summary.contributors.join(", ") || "—" },
    { value: summary.postPrint, label: "Post-print changes", sub: "Flagged for reprint" },
    { value: summary.prints, label: "Prints issued", sub: "All 3 documents per print" },
  ];
  return (
    <section className={`${styles.page} ${styles.cover}`} aria-label="Cover">
      <div className={styles.brand}>
        <NottinghamVenuesLogo height={40} />
        <span className={styles.brandLabel}>Allergen manager</span>
      </div>
      <div className={styles.coverTitleBlock}>
        <p className={styles.coverVenue}>{venueName} · Nottingham Venues</p>
        <h1 className={styles.coverTitle}>Change Log Archive</h1>
        <p className={styles.coverMonth}>{month}</p>
        <div className={styles.coverRule} />
        <p className={styles.coverFacts}>
          <span>{archive.ref}</span>
          <span>Generated {generatedLabel(archive.generatedAt)}</span>
          <span>Covers {coverage}</span>
        </p>
      </div>
      {archive.partial && (
        <div className={`banner banner-warn ${styles.partial}`}>
          <div className="banner-body">
            <strong>Partial record</strong> — covers {coverage}. Generated before month end. Changes made after the
            generation timestamp do not appear in this document.
          </div>
        </div>
      )}
      <div className={styles.summary}>
        <h2 className={styles.summaryTitle}>Summary</h2>
        <dl className={styles.figures}>
          {figures.map((f) => (
            // Label first for screen readers; the number shows on top (CSS order).
            <div key={f.label} className={styles.figure}>
              <dt className={styles.figureLabel}>{f.label}</dt>
              <dd className={styles.figureValue}>{f.value}</dd>
              <dd className={styles.figureSub}>{f.sub}</dd>
            </div>
          ))}
        </dl>
      </div>
      {footer}
    </section>
  );
}

function Page({ children, footer }: { children: ReactNode; footer: ReactNode }) {
  return (
    <section className={styles.page}>
      <div className={styles.pageContent} data-archive-page>
        {children}
      </div>
      {footer}
    </section>
  );
}

function Footer({ note, right }: { note: string; right: string }) {
  return (
    <footer className={styles.footer}>
      <span>{note}</span>
      <span className={styles.footerRight}>{right}</span>
    </footer>
  );
}

function DocumentLoading() {
  return (
    <div className={styles.desk}>
      <LoadingPlaceholder label="Loading archive">
        <Skeleton width={794} height={1123} style={{ maxWidth: "100%" }} />
      </LoadingPlaceholder>
    </div>
  );
}
